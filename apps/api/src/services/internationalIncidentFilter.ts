export interface ForeignCheckResult {
  isForeign: boolean;
  matchedTerm?: string;
  reason?: string;
}

/**
 * Universal evaluator for international/foreign incidents.
 * Analyzes both headline and article lead context.
 */
export function isForeignIncident(title: string, snippet: string = ''): ForeignCheckResult {
  if (!title && !snippet) {
    return { isForeign: false };
  }

  // Normalize Unicode (NFC) for robust Bengali script matching
  const normTitle = (title || '').normalize('NFC').toLowerCase();
  const normSnippet = (snippet || '').normalize('NFC').toLowerCase();
  const combined = `${normTitle} ${normSnippet}`;

  for (const keyword of GLOBAL_FOREIGN_TERMS) {
    const normKeyword = keyword.normalize('NFC').toLowerCase();

    // Prevent false positive on Bengali 'আসামি' (accused/convict, NOT Assam state)
    if (keyword.startsWith('আসাম')) {
      const isAccusedWord = /(?:আসামি|আসামির|আসামিদের|আসামিরা|আসামীর)/i.test(normTitle);
      const isAssamState = /(?:আসামে|আসাম\s+রাজ্য|আসামের)/i.test(normTitle);
      if (isAccusedWord && !isAssamState) {
        continue;
      }
    }

    // 1. Primary check: Headline explicitly mentions a foreign country, territory or city
    if (normTitle.includes(normKeyword)) {
      return {
        isForeign: true,
        matchedTerm: keyword,
        reason: `Headline explicitly references overseas country/city "${keyword}"`,
      };
    }

    // 2. Incident-association check in lead snippet:
    // Matches if the foreign term appears in close proximity to incident verbs
    const incidentActionRegex = new RegExp(
      `(?:${normKeyword})[\\s\\S]{0,35}(?:সড়ক দুর্ঘটনা|সড়ক দুর্ঘটনায়|সড়কে নিহত|দুর্ঘটনা|নিহত|আহত|হামলা|ছিনতাই|আগুনে|দাফন|লাশ|গুলি|গুলিবিদ্ধ|dead|killed|crash|accident|shot|injured)`,
      'i'
    );

    if (incidentActionRegex.test(combined)) {
      return {
        isForeign: true,
        matchedTerm: keyword,
        reason: `Article associates incident with overseas location "${keyword}"`,
      };
    }
  }

  return { isForeign: false };
}
